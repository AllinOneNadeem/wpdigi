        if ( $total_scanned > 0 ) {
            $total_possible = $total_scanned * 3;
            $total_issues   = $missing_meta_desc + $short_titles + $missing_featured;
            $seo_score      = max( 10, round( ( ( $total_possible - $total_issues ) / $total_possible ) * 100 ) );
